import Ajv from "ajv";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, writeFileSync } from "node:fs";
import { build } from "esbuild";
const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true } });
addFormats(ajv);
const validate = ajv.compile(
  JSON.parse(readFileSync("schemas/events.v1.json", "utf8")),
);
const result = await build({
  stdin: {
    contents: standaloneCode(ajv, validate),
    resolveDir: process.cwd(),
    loader: "js",
  },
  bundle: true,
  platform: "browser",
  format: "esm",
  outfile: "src/lib/validate-event.js",
  write: false,
  banner: { js: "// @ts-nocheck -- generated by AJV; do not edit" },
});
// esbuild labels bundled modules with their resolved path. A shared node_modules
// symlink must not make this tracked generated file depend on the worktree name.
const output = result.outputFiles?.[0]?.text;
if (!output) throw Error("AJV validator bundle is missing");
writeFileSync("src/lib/validate-event.js", output.replace(/(?:\.\.\/)+(?:[^/\n"']+\/)*?node_modules\//g, "node_modules/"));
