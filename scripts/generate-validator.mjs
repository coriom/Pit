import Ajv from 'ajv';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import {readFileSync} from 'node:fs';
import {build} from 'esbuild';
const ajv=new Ajv({allErrors:true,code:{source:true,esm:true}});
addFormats(ajv);
const validate=ajv.compile(JSON.parse(readFileSync('schemas/events.v1.json','utf8')));
await build({stdin:{contents:standaloneCode(ajv,validate),resolveDir:process.cwd(),loader:'js'},bundle:true,platform:'browser',format:'esm',outfile:'src/lib/validate-event.js',banner:{js:'// @ts-nocheck -- generated by AJV; do not edit'}});
