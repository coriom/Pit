import { readFileSync, readdirSync } from "node:fs";
import { join, relative } from "node:path";

const allowedConnect = new Set([
  "'self'",
  "https://api.cow.fi",
  "https://api.hyperliquid-testnet.xyz",
  "https://rpc.hyperliquid-testnet.xyz",
  "https://ethereum-sepolia-rpc.publicnode.com",
  "https://11155111.rpc.thirdweb.com",
]);
const analytics =
  /google-analytics\.com|googletagmanager\.com|analytics\.google\.com|api\.segment\.io|cdn\.segment\.com|api\.mixpanel\.com|posthog\.com|hotjar\.com|fullstory\.com|sentry\.io/i;
// Independent checks scan the full body: accepting one public URL cannot mask
// a second candidate beside it. No domain, file, or value is allowlisted.
const secretPatterns = [
  [
    "assignment",
    /(?:PRIVATE[_-]?KEY|API[_-]?KEY|API[_-]?SECRET|MNEMONIC|SEED[_-]?PHRASE|ACCESS[_-]?TOKEN)\s*[=:]\s*["']?[A-Za-z0-9_./+\-=]{16,}/i,
  ],
  ["private-key-pem", /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/i],
  ["url-userinfo", /https?:\/\/[^\s/:@"'<>]+:[^\s/@"'<>]+@[^\s"'<>]+/i],
  [
    "url-sensitive-query",
    /https?:\/\/[^\s"'<>]*[?&](?:api[_-]?key|api[_-]?token|token|secret|password|client[_-]?secret)=[A-Za-z0-9_%+.-]+/i,
  ],
  // A single opaque ID directly after /v2/ or /v3/ remains suspect. The old
  // rule crossed further path separators and caught ordinary documentation.
  [
    "url-opaque-version-id",
    /https?:\/\/[^\s"'<>]*?\/v[23]\/[A-Za-z0-9_-]{20,}(?![A-Za-z0-9_-])/i,
  ],
];
export function artifactSecretKind(body) {
  for (const [kind, pattern] of secretPatterns)
    if (pattern.test(body)) return kind;
  return null;
}
const mainnetExecution =
  /https:\/\/(?:api\.cow\.fi\/(?:mainnet|base|arbitrum)|api\.hyperliquid\.xyz\/(?:exchange|info)|rpc\.hyperliquid\.xyz\/[^"'\s]+)/i;
const analyticsPackage =
  /(?:analytics|telemetry|sentry|posthog|mixpanel|segment|hotjar|fullstory|react-ga)/i;

export function validateAnalyticsDependencies(files) {
  const pkg = JSON.parse(files.get("package.json")?.toString() || "{}");
  for (const name of Object.keys({
    ...pkg.dependencies,
    ...pkg.devDependencies,
  }))
    if (analyticsPackage.test(name))
      throw Error(`Direct analytics dependency: ${name}`);
  for (const [name, body] of files) {
    if (!/^src\/.*\.[cm]?[jt]sx?$/.test(name)) continue;
    const source = body.toString();
    if (
      /(?:\bfrom\s*|\bimport\s*\(|\brequire\s*\()\s*["'][^"']*(?:@metamask\/sdk-analytics|@astrojs\/telemetry|@sentry\/|posthog-js|mixpanel-browser|@segment\/analytics-next|react-ga4|firebase\/analytics)/i.test(
        source,
      )
    )
      throw Error(`Analytics import in app source: ${name}`);
  }
}

export function collectArtifacts(root = "dist") {
  const files = new Map();
  function visit(dir) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) visit(path);
      else
        files.set(
          relative(root, path).replaceAll("\\", "/"),
          readFileSync(path, "utf8"),
        );
    }
  }
  visit(root);
  return files;
}

// A Git deployment reads vercel.json at the repository root before the build.
// Keep its pinned CSP identical to the hashes generated by this exact build.
export function validateProjectVercelConfig(projectText, artifactText) {
  if (!projectText || !artifactText)
    throw Error("Missing project-root or built Vercel configuration");
  let project, artifact;
  try {
    project = JSON.parse(projectText);
    artifact = JSON.parse(artifactText);
  } catch {
    throw Error("Malformed project-root or built Vercel configuration");
  }
  const keys = ["$schema", "framework", "headers", "outputDirectory"];
  if (
    JSON.stringify(Object.keys(project).sort()) !== JSON.stringify(keys) ||
    project.$schema !== artifact.$schema ||
    project.framework !== null ||
    project.outputDirectory !== "dist" ||
    JSON.stringify(project.headers) !== JSON.stringify(artifact.headers)
  ) throw Error("Project-root Vercel headers or output directory differ from built configuration");
}

export function validateArtifacts(files) {
  for (const [name, body] of files) {
    if (/__pit-staging-accounting\//.test(name) ||
        /PIT_STAGING_ACCOUNTING_AUDIT_ONLY|PIT_STAGING_ACCEPTANCE_ONLY|__pit-staging-accounting|pit:staging-synthetic|staging-audit-access|staging-access\.mjs|staging-acceptance\.mjs|staging-diagnostics\.mjs|com\.vercel\.cli|x-vercel-protection-bypass/i.test(body))
      throw Error(`Staging accounting harness in production artifact: ${name}`);
  }
  const htmlFiles = [...files].filter(([name]) => name.endsWith(".html"));
  for (const page of [
    "index.html",
    "fees/index.html",
    "legal/index.html",
    "tools/index.html",
  ])
    if (!files.has(page)) throw Error(`Missing required static page: ${page}`);
  const headers = files.get("_headers");
  if (!headers) throw Error("Missing Cloudflare Pages response headers");
  const vercelText = files.get("vercel.json");
  if (!vercelText) throw Error("Missing Vercel static response headers");
  let vercel;
  try { vercel = JSON.parse(vercelText); }
  catch { throw Error("Malformed Vercel static response headers"); }
  const headerLines = headers.trimEnd().split("\n");
  const expectedHeaders = headerLines.slice(1).map((line) => {
    const match = line.match(/^  ([A-Za-z-]+): ([^\r\n]+)$/);
    if (!match) throw Error("Malformed static response header");
    return { key: match[1], value: match[2] };
  });
  if (headerLines[0] !== "/*" ||
      JSON.stringify(Object.keys(vercel).sort()) !== JSON.stringify(["$schema", "framework", "headers", "outputDirectory"]) ||
      vercel.framework !== null || vercel.outputDirectory !== "." ||
      !Array.isArray(vercel.headers) || vercel.headers.length !== 1 ||
      vercel.headers[0].source !== "/(.*)" ||
      JSON.stringify(vercel.headers[0].headers) !== JSON.stringify(expectedHeaders))
    throw Error("Vercel headers differ from the built static CSP and security headers");
  let externalExecutable = 0;
  for (const [name, body] of files) {
    if (/PIT_AUTONOMOUS_SIGNER_TEST_ONLY|\/\.pit\/test-operator\/|autonomous-signer(?:\.[cm]?[jt]s)?/i.test(body))
      throw Error(`Test signer or secret loader in production artifact: ${name}`);
    if (
      /\.map$/i.test(name) ||
      /sourceMappingURL\s*=|sourcesContent\s*:/i.test(body)
    )
      throw Error(`Source map leakage: ${name}`);
    if (analytics.test(body))
      throw Error(`Analytics endpoint in artifact: ${name}`);
    if (artifactSecretKind(body))
      throw Error(`Secret-like value in artifact: ${name}`);
    if (mainnetExecution.test(body))
      throw Error(`Mainnet execution endpoint in artifact: ${name}`);
    if (
      name.endsWith(".css") &&
      /(?:@import\s*(?:url\()?\s*["']?|url\(\s*["']?)\s*(?:https?:)?\/\//i.test(
        body,
      )
    )
      throw Error(`External CSS resource: ${name}`);
  }
  for (const [name, html] of htmlFiles) {
    const meta = html.match(
      /<meta\s+http-equiv="content-security-policy"\s+content="([^"]+)"/i,
    );
    if (!meta) throw Error(`Missing CSP meta: ${name}`);
    const csp = meta[1].replaceAll("&amp;", "&").replace(/;+$/, "");
    if (
      !headers.includes(
        `Content-Security-Policy: ${csp}; frame-ancestors 'none'`,
      )
    )
      throw Error(`HTTP CSP does not match HTML: ${name}`);
    if (/unsafe-eval|wasm-unsafe-eval|\bhttps?:\s|\*/i.test(csp))
      throw Error(`Forbidden CSP directive/source: ${name}`);
    const directives = new Map(
      csp
        .split(";")
        .map((part) => part.trim().split(/\s+/, 2))
        .filter((x) => x[0])
        .map(([key]) => [
          key,
          csp.match(new RegExp(`(?:^|;)\\s*${key}\\s+([^;]+)`))?.[1]?.trim(),
        ]),
    );
    const connect = new Set((directives.get("connect-src") || "").split(/\s+/));
    if (
      connect.size !== allowedConnect.size ||
      [...connect].some((x) => !allowedConnect.has(x))
    )
      throw Error(`Unexpected connect-src: ${name}`);
    if (
      !/^'self'(?:\s+'sha(?:256|384|512)-[A-Za-z0-9+/=]+')+$/.test(
        directives.get("script-src") || "",
      )
    )
      throw Error(`Script CSP lacks self and inline hashes: ${name}`);
    if (directives.get("style-src") !== "'self' 'unsafe-inline'")
      throw Error(`Unexpected style-src: ${name}`);
    const attribute = (tag, key) => {
      const match = tag.match(
        new RegExp(`\\b${key}\\s*=\\s*(?:"([^"]*)"|'([^']*)'|([^\\s>]+))`, "i"),
      );
      return match?.[1] ?? match?.[2] ?? match?.[3];
    };
    for (const tag of html.match(/<(?:script|link)\b[^>]*>/gi) || []) {
      const rel = attribute(tag, "rel")?.toLowerCase();
      const isStyle =
        /^<link\b/i.test(tag) &&
        (rel === "stylesheet" ||
          rel === "modulepreload" ||
          (rel === "preload" && attribute(tag, "as") === "script"));
      if (!/^<script\b/i.test(tag) && !isStyle) continue;
      const url = attribute(tag, /^<script\b/i.test(tag) ? "src" : "href");
      if (!url || !/^(?:https?:)?\/\//i.test(url)) continue;
      externalExecutable++;
      if (
        !/^sha(?:256|384|512)-[A-Za-z0-9+/=]+$/i.test(
          attribute(tag, "integrity") || "",
        ) ||
        attribute(tag, "crossorigin") !== "anonymous"
      )
        throw Error(`External executable/style lacks SRI and CORS: ${name}`);
    }
  }
  if (
    !headers.includes("X-Content-Type-Options: nosniff") ||
    !headers.includes("Referrer-Policy: no-referrer")
  )
    throw Error("Missing static security headers");
  return { html: htmlFiles.length, files: files.size, externalExecutable };
}

if (process.argv[1]?.endsWith("artifacts.mjs")) {
  try {
    const files = collectArtifacts();
    const result = validateArtifacts(files);
    validateProjectVercelConfig(readFileSync("vercel.json", "utf8"), files.get("vercel.json"));
    console.log(
      `PASS static artifacts: ${result.files} files; ${result.html} HTML pages; ${result.externalExecutable} external scripts/styles; project-root Vercel CSP, SRI, telemetry, secret, source-map and mainnet endpoint guards`,
    );
  } catch (error) {
    console.error(`STATIC ARTIFACT CHECK FAILED: ${error.message}`);
    process.exitCode = 1;
  }
}
