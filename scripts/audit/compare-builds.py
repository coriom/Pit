import json,pathlib,hashlib,subprocess
first=pathlib.Path('docs/audit/phase-f/build-1.manifest.json').read_bytes()
second=pathlib.Path('dist/build-manifest.json').read_bytes()
print('build-1 manifest hash:',json.loads(first)['hash'])
print('build-2 manifest hash:',json.loads(second)['hash'])
print('Complete manifests byte-identical:',first==second)
assert first==second
manifest=json.loads(second)
for name,digest in manifest['files'].items():
 assert hashlib.sha256((pathlib.Path('dist')/name).read_bytes()).hexdigest()==digest,name
print('Verified individual artifact digests:',len(manifest['files']))
# The build regenerates this validator; compare regenerated bytes to the audited release.
original=subprocess.check_output(['git','show','c65a14e:src/lib/validate-event.js'])
print('Regenerated validator equals phase-E validator:',original==pathlib.Path('src/lib/validate-event.js').read_bytes())
assert original==pathlib.Path('src/lib/validate-event.js').read_bytes()
