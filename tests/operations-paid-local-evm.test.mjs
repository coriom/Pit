import test from "node:test";
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { readFileSync } from "node:fs";
import { createPublicClient, createWalletClient, http, decodeEventLog, parseUnits } from "viem";
import { foundry } from "viem/chains";

const url = "http://127.0.0.1:9547";
const artifact = (source, name) => JSON.parse(readFileSync(`out/${source}.sol/${name}.json`, "utf8"));
const paidA = artifact("PitPaidOperations", "PitPaidOperations");
const creatorA = artifact("PitPaidTokenCreator", "PitPaidTokenCreator");
const mockA = artifact("PitMockUSDC", "PitMockUSDC");
const tokenA = artifact("PitTokens", "PitStandardToken");
const advancedA = artifact("PitTokens", "PitAdvancedToken");
const lockA = artifact("PitSchedules", "PitTokenLock");
const vestA = artifact("PitSchedules", "PitTokenVesting");
const rpc = async (method, params = []) => {
  const response = await fetch(url, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }) });
  const body = await response.json(); if (body.error) throw Error(`Anvil RPC ${body.error.code}`); return body.result;
};

test("five local paid paths execute atomically with exact mock-USDC receipts and state readbacks", { timeout: 120_000 }, async (t) => {
  const anvil = spawn("anvil", ["--host", "127.0.0.1", "--port", "9547", "--chain-id", "31337", "--accounts", "5", "--silent"], { stdio: "ignore" });
  t.after(() => anvil.kill("SIGTERM"));
  for (let attempt = 0; attempt < 50; ++attempt) { try { if (await rpc("eth_chainId") === "0x7a69") break; } catch { /* Anvil starting */ } await new Promise((r) => setTimeout(r, 100)); }
  assert.equal(await rpc("eth_chainId"), "0x7a69");
  const [payer, recipient, beneficiary, merchant] = await rpc("eth_accounts");
  const publicClient = createPublicClient({ chain: foundry, transport: http(url) });
  const wallet = createWalletClient({ account: payer, chain: foundry, transport: http(url) });
  const recipientWallet = createWalletClient({ account: beneficiary, chain: foundry, transport: http(url) });
  const wait = async (hash) => { const receipt = await publicClient.waitForTransactionReceipt({ hash }); assert.equal(receipt.status, "success"); return receipt; };
  const deploy = async (a, args) => { const receipt = await wait(await wallet.deployContract({ abi: a.abi, bytecode: a.bytecode.object, args })); assert.ok(receipt.contractAddress); return receipt.contractAddress; };
  const write = async (address, abi, functionName, args) => wait(await wallet.writeContract({ address, abi, functionName, args }));
  const read = (address, abi, functionName, args = []) => publicClient.readContract({ address, abi, functionName, args });
  const sameAddress = (actual, expected) => assert.equal(actual.toLowerCase(), expected.toLowerCase());
  const decode = (receipt, abi, eventName) => receipt.logs.map((log) => { try { return decodeEventLog({ abi, data: log.data, topics: log.topics }); } catch { return undefined; } }).find((e) => e?.eventName === eventName);
  const mock = await deploy(mockA, [payer]);
  assert.equal(await read(mock, mockA.abi, "decimals"), 6);
  const prices = { standard: 49_000_000n, advanced: 149_000_000n, multiBase: 3_000_000n, multiPerRecipient: 100_000n, multiCap: 49_000_000n, lockFee: 39_000_000n, vestingFee: 79_000_000n };
  const paid = await deploy(paidA, [mock, merchant, payer, prices]);
  const creator = await deploy(creatorA, [mock, merchant, payer, prices]);
  sameAddress(await read(paid, paidA.abi, "feeRecipient"), merchant);
  sameAddress(await read(paid, paidA.abi, "paymentToken"), mock);
  const quote = (n, fee) => ({ intentId: `0x${n.toString(16).padStart(64, "0")}`, version: 1n, maxFee: fee, deadline: BigInt(Math.floor(Date.now() / 1000)) + 900n });
  // Anvil's timestamp can be newer or older than the OS clock; derive deadline from its block.
  const makeQuote = async (n, fee) => ({ ...quote(n, fee), deadline: (await publicClient.getBlock()).timestamp + 900n });
  const paidWrite = async (functionName, args, n, fee) => {
    const target = functionName.startsWith("createStandard") || functionName.startsWith("createAdvanced") ? creator : paid;
    const abi = target === creator ? creatorA.abi : paidA.abi;
    await write(mock, mockA.abi, "approve", [target, fee]);
    const receipt = await write(target, abi, functionName, [...args, await makeQuote(n, fee)]);
    const feeEvent = decode(receipt, abi, "FeePaid"), operationEvent = decode(receipt, abi, "OperationExecuted");
    sameAddress(feeEvent?.args.payer, payer); sameAddress(feeEvent?.args.recipient, merchant); assert.equal(feeEvent?.args.amount, fee);
    sameAddress(operationEvent?.args.payer, payer); assert.equal(operationEvent?.args.intentId, feeEvent.args.intentId);
    assert.equal(await read(mock, mockA.abi, "allowance", [payer, target]), 0n);
    assert.equal(await read(target, abi, "usedIntent", [payer, feeEvent.args.intentId]), true);
    return { receipt, result: operationEvent.args.result };
  };
  const standard = await paidWrite("createStandard", ["Paid Demo", "PAY", parseUnits("1000", 18), payer], 1, prices.standard);
  const token = standard.result;
  assert.equal(await read(token, tokenA.abi, "totalSupply"), parseUnits("1000", 18));
  assert.equal(await read(token, tokenA.abi, "balanceOf", [payer]), parseUnits("1000", 18));
  const advancedConfig = { name: "Paid Advanced", symbol: "PAD", supply: parseUnits("10", 18), cap: parseUnits("20", 18), recipient: payer, minting: true, burning: true, pausing: true };
  const advanced = await paidWrite("createAdvanced", [advancedConfig], 2, prices.advanced);
  const role = await read(advanced.result, advancedA.abi, "DEFAULT_ADMIN_ROLE");
  assert.equal(await read(advanced.result, advancedA.abi, "hasRole", [role, payer]), true);
  assert.equal(await read(advanced.result, advancedA.abi, "hasRole", [role, creator]), false);
  assert.equal(await read(advanced.result, advancedA.abi, "totalSupply"), advancedConfig.supply);
  assert.equal(await read(paid, paidA.abi, "multiFee", [2n]), 3_200_000n);
  await write(token, tokenA.abi, "approve", [paid, parseUnits("10", 18)]);
  const multisend = await paidWrite("multiSend", [token, [recipient, beneficiary], [parseUnits("7", 18), parseUnits("3", 18)]], 3, 3_200_000n);
  assert.equal(await read(token, tokenA.abi, "balanceOf", [recipient]), parseUnits("7", 18));
  assert.equal(await read(token, tokenA.abi, "balanceOf", [beneficiary]), parseUnits("3", 18));
  assert.equal(await read(token, tokenA.abi, "balanceOf", [paid]), 0n);
  assert.equal(await read(token, tokenA.abi, "allowance", [payer, paid]), 0n);
  assert.equal(multisend.result, "0x0000000000000000000000000000000000000000");
  const now = (await publicClient.getBlock()).timestamp;
  await write(token, tokenA.abi, "approve", [paid, parseUnits("25", 18)]);
  const lock = await paidWrite("createLock", [token, parseUnits("25", 18), beneficiary, now + 100n], 4, prices.lockFee);
  sameAddress(await read(lock.result, lockA.abi, "beneficiary"), beneficiary);
  assert.equal(await read(lock.result, lockA.abi, "deposited"), parseUnits("25", 18));
  assert.equal(await read(token, tokenA.abi, "balanceOf", [paid]), 0n);
  await assert.rejects(publicClient.simulateContract({ address: lock.result, abi: lockA.abi, functionName: "release", account: beneficiary }));
  await rpc("evm_setNextBlockTimestamp", [Number(now + 100n)]); await rpc("evm_mine");
  await wait(await recipientWallet.writeContract({ address: lock.result, abi: lockA.abi, functionName: "release" }));
  assert.equal(await read(token, tokenA.abi, "balanceOf", [beneficiary]), parseUnits("28", 18));
  const next = (await publicClient.getBlock()).timestamp;
  await write(token, tokenA.abi, "approve", [paid, 101n]);
  const vest = await paidWrite("createVesting", [{ token, amount: 101n, beneficiary, start: next + 100n, duration: 100n, cliff: next + 150n }], 5, prices.vestingFee);
  assert.equal(await read(vest.result, vestA.abi, "funded"), true);
  assert.equal(await read(vest.result, vestA.abi, "allocation"), 101n);
  await rpc("evm_setNextBlockTimestamp", [Number(next + 150n)]); await rpc("evm_mine");
  assert.equal(await read(vest.result, vestA.abi, "releasable"), 50n);
  await wait(await recipientWallet.writeContract({ address: vest.result, abi: vestA.abi, functionName: "release" }));
  await rpc("evm_setNextBlockTimestamp", [Number(next + 200n)]); await rpc("evm_mine");
  await wait(await recipientWallet.writeContract({ address: vest.result, abi: vestA.abi, functionName: "release" }));
  assert.equal(await read(vest.result, vestA.abi, "released"), 101n);
  assert.equal(await read(mock, mockA.abi, "balanceOf", [merchant]), 49_000_000n + 149_000_000n + 3_200_000n + 39_000_000n + 79_000_000n);
  assert.equal(await read(mock, mockA.abi, "balanceOf", [paid]), 0n);
  // Real reverted transaction: service fee transfer, token deployment, and intent mark all roll back.
  await write(mock, mockA.abi, "approve", [creator, prices.standard]);
  const merchantBefore = await read(mock, mockA.abi, "balanceOf", [merchant]);
  const badQuote = await makeQuote(6, prices.standard);
  const failedHash = await wallet.writeContract({ address: creator, abi: creatorA.abi, functionName: "createStandard", args: ["", "BAD", 1n, payer, badQuote] });
  const failedReceipt = await publicClient.waitForTransactionReceipt({ hash: failedHash });
  assert.equal(failedReceipt.status, "reverted");
  assert.equal(await read(mock, mockA.abi, "balanceOf", [merchant]), merchantBefore);
  assert.equal(await read(creator, creatorA.abi, "usedIntent", [payer, badQuote.intentId]), false);
  console.log(JSON.stringify({ localChainId: 31337, mockPaymentToken: mock, paidAssetRouter: paid, paidCreatorRouter: creator, paidReceipts: [standard, advanced, multisend, lock, vest].map((x) => ({ hash: x.receipt.transactionHash, gasUsed: x.receipt.gasUsed.toString() })), revertedHash: failedHash, merchantMockMicro: merchantBefore.toString(), realUSDC: false, externalWrites: 0 }));
});
